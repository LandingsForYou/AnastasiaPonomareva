function normalizeCertificateIndex(index) {
  const total = certificates.length;

  if (!total) return 0;

  if (index < 0) {
    return total - 1;
  }

  if (index >= total) {
    return 0;
  }

  return index;
}

function setCertificateClasses() {
  certificates.forEach((certificate, index) => {
    certificate.classList.remove(
      "is-active",
      "is-prev",
      "is-next",
      "is-prev-2",
      "is-next-2",
    );

    if (index === certificateIndex) {
      certificate.classList.add("is-active");
    }

    if (index === certificateIndex - 1) {
      certificate.classList.add("is-prev");
    }

    if (index === certificateIndex + 1) {
      certificate.classList.add("is-next");
    }

    if (index === certificateIndex - 2) {
      certificate.classList.add("is-prev-2");
    }

    if (index === certificateIndex + 2) {
      certificate.classList.add("is-next-2");
    }
  });
}

